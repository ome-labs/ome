#!/usr/bin/env node
// Renders the Homebrew formula (Formula/ome.rb in ome-labs/homebrew-tap) for a release from its SHA256SUMS.
//
//   node scripts/packaging/formula.ts <SHA256SUMS> [<download-base>]
//
// The download base defaults to the GitHub release of this version; a dry run passes a file:// directory.
import { readFileSync } from "node:fs";

import { PLATFORMS, version } from "./targets.ts";

const [sumsPath, baseArg] = process.argv.slice(2);
if (!sumsPath) {
  process.stderr.write("usage: formula.ts <SHA256SUMS> [<download-base>]\n");
  process.exit(2);
}
const release = version();
const base = baseArg ?? `https://github.com/ome-labs/ome/releases/download/v${release}`;
const sums = new Map(
  readFileSync(sumsPath, "utf8")
    .trim()
    .split("\n")
    .map((line) => {
      const [sum, file] = line.trim().split(/\s+\*?/);
      return [file, sum] as const;
    }),
);

function block(name: string): string {
  const file = `ome-${release}-${name}.tar.gz`;
  const sum = sums.get(file);
  if (!sum) {
    throw new Error(`${file} is not in ${sumsPath}`);
  }
  return `url "${base}/${file}"\n      sha256 "${sum}"`;
}

const has = (name: string) => PLATFORMS.some((p) => p.name === name);
if (!has("darwin-arm64") || !has("linux-x64") || !has("linux-arm64")) {
  throw new Error("the formula template expects darwin-arm64, linux-x64 and linux-arm64");
}

process.stdout
  .write(`# Generated by scripts/packaging/formula.ts in ome-labs/ome for each release; do not edit by hand.
class Ome < Formula
  desc "Private k-of-n multisig on Aztec with threshold viewing"
  homepage "https://ome.network"
  version "${release}"
  license "Apache-2.0"

  on_macos do
    on_arm do
      ${block("darwin-arm64")}
    end
  end

  on_linux do
    on_intel do
      ${block("linux-x64")}
    end
    on_arm do
      ${block("linux-arm64")}
    end
  end

  depends_on "node@24"

  def install
    libexec.install Dir["*"]
    # The daemon runs with Homebrew's Node, also when a login service starts it without PATH.
    inreplace libexec/"bin/omed", 'node_default=""', %Q(node_default="#{Formula["node@24"].opt_bin}/node")
    bin.install_symlink libexec/"bin/ome", libexec/"bin/omed", libexec/"bin/ome-keeper"
  end

  def caveats
    <<~EOS
      Create a profile with:
        ome init
      Keep your keeper online while your laptop sleeps by running the daemon as a login service:
        ome daemon install-service
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/ome --version")
    assert_match version.to_s, shell_output("#{bin}/ome-keeper --version")
  end
end
`);
